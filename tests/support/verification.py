"""
The verification record: verification tests report what they measured, and the run writes a report from it.

    def test_something(verify):
        ...
        verify("Clamped circular plate (Kirchhoff)", "f(0,1) error", err, bound=0.005, reference="Leissa 1969",
               unit="rel.", note="3D elasticity, h/a = 0.02")
        assert err < 0.005

    pytest --slow --verification-report docs/guide/verification_report.rst

Each record: area, case, quantity, value, bound (the test's own tolerance, or None when only reported), kind
("max": value ≤ bound, "min": value ≥ bound, "range": bound = (lo, hi)), reference (the analytical solution or
source), note; the outcome of the test that recorded it is added at the end of the run. The report groups the
records by area and case, one table row per record, and states the machine, versions and date.
"""
from __future__ import annotations

import datetime
import json
import platform
from dataclasses import asdict, dataclass, field
from pathlib import Path


@dataclass
class Record:
    area: str
    case: str
    quantity: str
    value: float
    bound: object = None
    kind: str = "max"
    reference: str = ""
    unit: str = ""
    note: str = ""
    test: str = ""
    outcome: str = ""

    @property
    def within(self) -> bool | None:
        if self.bound is None:
            return None
        if self.kind == "max":
            return self.value <= self.bound
        if self.kind == "min":
            return self.value >= self.bound
        lo, hi = self.bound
        return lo <= self.value <= hi


@dataclass
class Recorder:
    records: list = field(default_factory=list)

    def add(self, test, area, case, quantity, value, bound=None, kind="max", reference="", unit="", note=""):
        v = float(value)
        b = tuple(float(x) for x in bound) if isinstance(bound, (tuple, list)) else (
            None if bound is None else float(bound))
        self.records.append(Record(area, case, quantity, v, b, "range" if isinstance(b, tuple) else kind,
                                   reference, unit, note, test))

    def set_outcome(self, test, outcome):
        for r in self.records:
            if r.test == test:
                r.outcome = outcome

    @classmethod
    def from_json(cls, path) -> "Recorder":
        data = json.loads(Path(path).read_text())
        return cls([Record(**{**d, "bound": tuple(d["bound"]) if isinstance(d["bound"], list) else d["bound"]})
                    for d in data])

    def save_json(self, path):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(json.dumps([asdict(r) for r in self.records], indent=1))

    # ── report ──────────────────────────────────────────────────────────────
    def rst(self) -> str:
        import loudpy
        import numpy
        import scipy
        now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        lines = ["Verification report", "===================", "",
                 ".. This file is generated by ``pytest --slow --verification-report <this file>``: do not edit.", "",
                 f"Generated {now} with loudpy {loudpy.__version__} (NumPy {numpy.__version__}, SciPy "
                 f"{scipy.__version__}, Python {platform.python_version()}, {platform.system()} "
                 f"{platform.machine()}). Every number below was measured by the test named next to it, in the "
                 f"same run; the bound is that test's own tolerance (\"—\": reported, not gated).", ""]
        n_tests = len({r.test for r in self.records})
        passed = len({r.test for r in self.records if r.outcome == "passed"})
        lines += [f"**{len(self.records)} measured quantities from {n_tests} tests; {passed} of the tests passed.**",
                  ""]
        areas = {}
        for r in self.records:
            areas.setdefault(r.area, {}).setdefault(r.case, []).append(r)
        for area, cases in areas.items():
            lines += [_esc(area), "-" * len(_esc(area)), ""]
            for case, recs in cases.items():
                lines += [_esc(case), "~" * len(_esc(case)), ""]
                ref = sorted({r.reference for r in recs if r.reference})
                notes = sorted({r.note for r in recs if r.note})
                if ref:
                    lines += ["Reference: " + _esc("; ".join(ref)) + ".", ""]
                if notes:
                    lines += [_esc(" ".join(notes)), ""]
                lines += [".. list-table::", "   :header-rows: 1", "   :widths: 40 16 16 10 18", "",
                          "   * - quantity", "     - value", "     - bound", "     - status", "     - test"]
                for r in recs:
                    status = {True: "within", False: "**outside**", None: "reported"}[r.within]
                    if r.outcome and r.outcome != "passed":
                        status += f" (test {r.outcome})"
                    lines += [f"   * - {_esc(r.quantity)}" + (f" [{r.unit}]" if r.unit else ""),
                              f"     - {_fmt(r.value)}", f"     - {_bound(r)}", f"     - {status}",
                              f"     - ``{r.test.split('::')[-1]}``"]
                lines.append("")
        return "\n".join(lines) + "\n"


def _esc(text: str) -> str:
    """Free text in reStructuredText: escape the inline markup characters."""
    for ch in ("\\", "|", "*", "`", "_"):
        text = text.replace(ch, "\\" + ch)
    return text


def _fmt(v: float) -> str:
    if v == 0:
        return "0"
    a = abs(v)
    return f"{v:.3g}" if 1e-3 <= a < 1e4 else f"{v:.2e}"


def _bound(r: Record) -> str:
    if r.bound is None:
        return "—"
    if r.kind == "range":
        return f"[{_fmt(r.bound[0])}, {_fmt(r.bound[1])}]"
    return ("≤ " if r.kind == "max" else "≥ ") + _fmt(r.bound)
